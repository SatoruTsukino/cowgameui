#!/usr/bin/env node
// Phase 6 T1: generates the shared design tokens from tokens.json (no npm deps).
//   node tools/gen-tokens.mjs           # writes roblox/src/shared/CowHUD/Tokens.luau + the token regions in index.html
//   node tools/gen-tokens.mjs --check   # exit code 1 if either output is stale
// index.html stays one hand-authored file: only the text between `tokens:<name>:start` and `tokens:<name>:end`
// markers is rewritten. Everything else that uses the tokens reads them at runtime (TOKENS in JS, Tokens in Luau).

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const TOKENS = resolve(ROOT, 'tokens.json');
const LUAU = resolve(ROOT, 'roblox/src/shared/CowHUD/Tokens.luau');
const HTML = resolve(ROOT, 'index.html');
const HEADER = 'generated by tools/gen-tokens.mjs from tokens.json; do not edit';

// `$comment` keys document tokens.json and are not tokens.
function strip(value) {
    if (Array.isArray(value)) return value.map(strip);
    if (value && typeof value === 'object') {
        return Object.fromEntries(Object.entries(value).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, strip(v)]));
    }
    return value;
}

const tokens = strip(JSON.parse(readFileSync(TOKENS, 'utf8')));
const { palette, sizes } = tokens;

// Same role → CSS variable map as applyThemePreset in index.html (ROLE_VARS).
const ROLE_VARS = {
    Card: '--theme-card-bg', Screen: '--theme-screen-bg', Subtle: '--theme-fill-subtle', Fill: '--theme-fill-primary',
    Border: '--theme-border', Accent: '--theme-accent', Text: '--theme-text-main', Danger: '--theme-danger',
};
for (const name of palette.order) {
    const preset = palette.presets[name];
    if (!preset) throw new Error(`palette.order names a missing preset: ${name}`);
    for (const role of Object.keys(ROLE_VARS)) {
        if (!/^#[0-9a-f]{6}$/.test(preset[role] ?? '')) throw new Error(`${name}.${role} must be a #rrggbb lowercase hex`);
    }
}

// ---------- Luau ----------
const luaKey = k => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`);
function luau(value, indent) {
    const pad = '\t'.repeat(indent + 1), end = '\t'.repeat(indent);
    if (Array.isArray(value)) {
        return value.every(v => typeof v !== 'object')
            ? `{ ${value.map(v => luau(v, indent)).join(', ')} }`
            : `{\n${value.map(v => `${pad}${luau(v, indent + 1)},`).join('\n')}\n${end}}`;
    }
    if (value && typeof value === 'object') {
        return `{\n${Object.entries(value).map(([k, v]) => `${pad}${luaKey(k)} = ${luau(v, indent + 1)},`).join('\n')}\n${end}}`;
    }
    return typeof value === 'string' ? JSON.stringify(value) : String(value);
}
const luauOut = `-- Shared design tokens (${HEADER}).
-- Pure data, no Roblox APIs, so plain \`luau\` tools can require it. Colours are #rrggbb strings (Theme converts them).

local function freeze(t)
	for _, v in t do
		if type(v) == "table" then
			freeze(v)
		end
	end
	return table.freeze(t)
end

return freeze(${luau(tokens, 0)})
`;

// ---------- index.html regions ----------
const px = n => `${n}px`;
const phone = key => sizes[key][1];
const mono = palette.presets[palette.order[0]];
const regions = {
    // Base CSS variables = the first preset, so the page is themed before any script runs.
    root: [
        ':root {',
        `    --theme-screen-bg: ${mono.Screen};`,
        `    --theme-grid-dot: ${mono.Fill};`,
        ...Object.entries(ROLE_VARS).filter(([role]) => role !== 'Screen').map(([role, v]) => `    ${v}: ${mono[role]};`),
        '}',
    ],
    // Phone preset: boxes holding text grow like Roblox Theme.size (second value of each tokens.json size pair).
    phone: [
        `.game-screen.aspect-19-5-9 .ps-backpack { width: ${px(phone('SidebarWidth'))} !important; height: ${px(phone('BackpackHeight'))} !important; }`,
        `.game-screen.aspect-19-5-9 .ps-square { width: ${px(phone('SidebarWidth'))} !important; height: ${px(phone('SidebarWidth'))} !important; }`,
        `.game-screen.aspect-19-5-9 .ps-herd-sq { width: ${px(phone('HerdSquare'))} !important; height: ${px(phone('HerdSquare'))} !important; }`,
        // Negative margin keeps the grown satellite centred on its desktop-size arc slot.
        `.game-screen.aspect-19-5-9 .ps-sat { width: ${px(phone('Satellite'))} !important; height: ${px(phone('Satellite'))} !important; margin: ${px((sizes.Satellite[0] - sizes.Satellite[1]) / 2)}; }`,
        `.game-screen.aspect-19-5-9 .ps-tool { width: ${px(phone('Tool'))} !important; height: ${px(phone('Tool'))} !important; }`,
        `.game-screen.aspect-19-5-9 #leftSidebar, .game-screen.aspect-19-5-9 #leftSidebarStandard { gap: ${px(phone('SidebarGap'))}; }`,
    ],
    js: [`const TOKENS = ${JSON.stringify(tokens)};`],
};

function fillRegions(html) {
    for (const [name, lines] of Object.entries(regions)) {
        const re = new RegExp(`^([ \\t]*)(/\\*|//) tokens:${name}:start[^\\n]*\\n[\\s\\S]*?^[ \\t]*(?:/\\*|//) tokens:${name}:end[^\\n]*$`, 'm');
        const match = html.match(re);
        if (!match) throw new Error(`index.html is missing the tokens:${name}:start / tokens:${name}:end markers`);
        const [, indent, open] = match;
        const close = open === '/*' ? ' */' : '';
        const body = lines.map(line => indent + line).join('\n');
        const block = `${indent}${open} tokens:${name}:start (${HEADER})${close}\n${body}\n${indent}${open} tokens:${name}:end${close}`;
        html = html.replace(re, () => block);
    }
    return html;
}

const outputs = [[LUAU, luauOut], [HTML, fillRegions(readFileSync(HTML, 'utf8'))]];
const check = process.argv.includes('--check');
let stale = 0;
for (const [file, content] of outputs) {
    let current = null;
    try { current = readFileSync(file, 'utf8'); } catch {}
    if (current === content) continue;
    if (check) {
        console.error(`STALE ${file.slice(ROOT.length + 1)}: run node tools/gen-tokens.mjs`);
        stale++;
    } else {
        writeFileSync(file, content);
        console.log(`wrote ${file.slice(ROOT.length + 1)}`);
    }
}
if (check && !stale) console.log('tokens up to date');
process.exit(stale ? 1 : 0);
